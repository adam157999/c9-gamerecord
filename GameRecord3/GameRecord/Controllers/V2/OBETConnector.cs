		public List<Obet.model.ReportResult> GetBrandCompletedGameResultsV2(string langId, DateTime dateFrom, DateTime dateTo)
		{
			api = new Obet.Obet(apiUrl, apiKey, agentId, timeOutSec);
			langId = GetGameLanguage(gameID, langId);
			var apiCall = api.GetReport(langId, dateFrom.ToString("yyyyMMddHHmmss"), dateTo.ToString("yyyyMMddHHmmss"));

			InsertLog(gameID, "OBETGameRecord", "request", api.TargetApiUrl, "response", api.Response, "dateFrom", dateFrom.ToString("yyyyMMddHHmmss"), "dateTo", dateTo.ToString("yyyyMMddHHmmss"));

			targetApiUrl = api.Request;
			request = api.Request;
			response = api.Response;

			if (apiCall)
			{
				return api.GetReportResponse.data;
			}
